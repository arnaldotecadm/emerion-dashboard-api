CREATE TABLE customer_quotation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id VARCHAR(64) NOT NULL,
    cnpj_empresa VARCHAR(20) NOT NULL,
    codigo_empresa INTEGER NOT NULL,
    codigo_cliente INTEGER NOT NULL,
    customer_external_id BIGINT NOT NULL,
    dteres DATE NOT NULL,
    numero_pedido VARCHAR(32) NOT NULL,
    data_pedido DATE NOT NULL,
    total_pedido_com_impostos NUMERIC(19, 4) NOT NULL,
    total_pedido_sem_impostos NUMERIC(19, 4) NOT NULL,
    cpf_cnpj VARCHAR(20),
    status_pedido VARCHAR(45),
    total_ipi NUMERIC(19, 4) NOT NULL,
    total_icms NUMERIC(19, 4) NOT NULL,
    total_pis NUMERIC(19, 4) NOT NULL,
    total_cofins NUMERIC(19, 4) NOT NULL,
    total_substituicao_tributaria NUMERIC(19, 4) NOT NULL,
    total_desconto_incondicional NUMERIC(19, 4) NOT NULL,
    total_frete NUMERIC(19, 4) NOT NULL,
    total_seguro NUMERIC(19, 4) NOT NULL,
    total_outras_despesas NUMERIC(19, 4) NOT NULL,
    vendedor_external_id BIGINT,
    atendente_cod VARCHAR(64),
    regime_tributario VARCHAR(64),
    nome_regime_tributario VARCHAR(128),
    codigo_padrao_faturamento VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_customer_quotation_cnpj_external_id UNIQUE (cnpj_empresa, external_id)
);
