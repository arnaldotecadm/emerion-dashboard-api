package br.com.vertice.emerion_dashboard.domain.customerquotation

import java.math.BigDecimal
import java.time.Instant
import java.time.LocalDate

data class CustomerQuotation(
    val id: Long?,
    val externalId: String,
    val cnpjEmpresa: String,
    val codigoEmpresa: Int,
    val codigoCliente: Int,
    val customerExternalId: Long,
    val dteres: LocalDate,
    val numeroPedido: String,
    val dataPedido: LocalDate,
    val totalPedidoComImpostos: BigDecimal,
    val totalPedidoSemImpostos: BigDecimal,
    val cpfCnpj: String?,
    val statusPedido: String?,
    val totalIpi: BigDecimal,
    val totalIcms: BigDecimal,
    val totalPis: BigDecimal,
    val totalCofins: BigDecimal,
    val totalSubstituicaoTributaria: BigDecimal,
    val totalDescontoIncondicional: BigDecimal,
    val totalFrete: BigDecimal,
    val totalSeguro: BigDecimal,
    val totalOutrasDespesas: BigDecimal,
    val vendedorExternalId: Long?,
    val atendenteCod: String?,
    val regimeTributario: String?,
    val nomeRegimeTributario: String?,
    val codigoPadraoFaturamento: String?,
    val createdAt: Instant,
    val updatedAt: Instant,
) {
    companion object {
        fun newFromIngestion(
            externalId: String,
            cnpjEmpresa: String,
            codigoEmpresa: Int,
            codigoCliente: Int,
            customerExternalId: Long,
            dteres: LocalDate,
            numeroPedido: String,
            dataPedido: LocalDate,
            totalPedidoComImpostos: BigDecimal,
            totalPedidoSemImpostos: BigDecimal,
            cpfCnpj: String?,
            statusPedido: String?,
            totalIpi: BigDecimal,
            totalIcms: BigDecimal,
            totalPis: BigDecimal,
            totalCofins: BigDecimal,
            totalSubstituicaoTributaria: BigDecimal,
            totalDescontoIncondicional: BigDecimal,
            totalFrete: BigDecimal,
            totalSeguro: BigDecimal,
            totalOutrasDespesas: BigDecimal,
            vendedorExternalId: Long?,
            atendenteCod: String?,
            regimeTributario: String?,
            nomeRegimeTributario: String?,
            codigoPadraoFaturamento: String?,
            now: Instant,
        ) = CustomerQuotation(
            id = null,
            externalId = externalId,
            cnpjEmpresa = cnpjEmpresa,
            codigoEmpresa = codigoEmpresa,
            codigoCliente = codigoCliente,
            customerExternalId = customerExternalId,
            dteres = dteres,
            numeroPedido = numeroPedido,
            dataPedido = dataPedido,
            totalPedidoComImpostos = totalPedidoComImpostos,
            totalPedidoSemImpostos = totalPedidoSemImpostos,
            cpfCnpj = cpfCnpj,
            statusPedido = statusPedido,
            totalIpi = totalIpi,
            totalIcms = totalIcms,
            totalPis = totalPis,
            totalCofins = totalCofins,
            totalSubstituicaoTributaria = totalSubstituicaoTributaria,
            totalDescontoIncondicional = totalDescontoIncondicional,
            totalFrete = totalFrete,
            totalSeguro = totalSeguro,
            totalOutrasDespesas = totalOutrasDespesas,
            vendedorExternalId = vendedorExternalId,
            atendenteCod = atendenteCod,
            regimeTributario = regimeTributario,
            nomeRegimeTributario = nomeRegimeTributario,
            codigoPadraoFaturamento = codigoPadraoFaturamento,
            createdAt = now,
            updatedAt = now,
        )
    }

    fun mergeFromIngestion(
        codigoEmpresa: Int,
        codigoCliente: Int,
        customerExternalId: Long,
        dteres: LocalDate,
        numeroPedido: String,
        dataPedido: LocalDate,
        totalPedidoComImpostos: BigDecimal,
        totalPedidoSemImpostos: BigDecimal,
        cpfCnpj: String?,
        statusPedido: String?,
        totalIpi: BigDecimal,
        totalIcms: BigDecimal,
        totalPis: BigDecimal,
        totalCofins: BigDecimal,
        totalSubstituicaoTributaria: BigDecimal,
        totalDescontoIncondicional: BigDecimal,
        totalFrete: BigDecimal,
        totalSeguro: BigDecimal,
        totalOutrasDespesas: BigDecimal,
        vendedorExternalId: Long?,
        atendenteCod: String?,
        regimeTributario: String?,
        nomeRegimeTributario: String?,
        codigoPadraoFaturamento: String?,
        now: Instant,
    ) = copy(
        codigoEmpresa = codigoEmpresa,
        codigoCliente = codigoCliente,
        customerExternalId = customerExternalId,
        dteres = dteres,
        numeroPedido = numeroPedido,
        dataPedido = dataPedido,
        totalPedidoComImpostos = totalPedidoComImpostos,
        totalPedidoSemImpostos = totalPedidoSemImpostos,
        cpfCnpj = cpfCnpj,
        statusPedido = statusPedido,
        totalIpi = totalIpi,
        totalIcms = totalIcms,
        totalPis = totalPis,
        totalCofins = totalCofins,
        totalSubstituicaoTributaria = totalSubstituicaoTributaria,
        totalDescontoIncondicional = totalDescontoIncondicional,
        totalFrete = totalFrete,
        totalSeguro = totalSeguro,
        totalOutrasDespesas = totalOutrasDespesas,
        vendedorExternalId = vendedorExternalId,
        atendenteCod = atendenteCod,
        regimeTributario = regimeTributario,
        nomeRegimeTributario = nomeRegimeTributario,
        codigoPadraoFaturamento = codigoPadraoFaturamento,
        updatedAt = now,
    )
}
